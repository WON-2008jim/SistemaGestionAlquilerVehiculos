    private void btnIniciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarActionPerformed
        // 1. Obtener datos de los campos
        String usuario = txtNombre.getText().trim();
        String clave = new String(pfContra.getPassword()).trim();

        // 2. Validar campos vacíos
        if (usuario.isEmpty() || clave.isEmpty()) {
            JOptionPane.showMessageDialog(this, 
                "Por favor, ingrese el usuario y la contraseña.", 
                "Campos Vacíos", 
                JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 3. Consultar en la base de datos con el gestor
        GestorEmpleados gestorEmpleados = new GestorEmpleados();
        Empleado empleadoAutenticado = gestorEmpleados.autenticar(usuario, clave);

        // 4. Evaluar si las credenciales son correctas
        if (empleadoAutenticado != null) {
            JOptionPane.showMessageDialog(this, 
                "¡Bienvenido al sistema, " + empleadoAutenticado.getNombre() + "!", 
                "Acceso Concedido", 
                JOptionPane.INFORMATION_MESSAGE);

            // Abrir el Menú Principal
            MenuPrincipal menu = new MenuPrincipal();
            menu.setVisible(true);
            menu.setLocationRelativeTo(null);

            // Cerrar la ventana de login
            this.dispose();
            
        } else {
            JOptionPane.showMessageDialog(this, 
                "Usuario o contraseña incorrectos.", 
                "Error de Autenticación", 
                JOptionPane.ERROR_MESSAGE);
            
            // Limpiar contraseña y enfocar usuario por seguridad
            pfContra.setText("");
            txtNombre.requestFocus();
        }
    }//GEN-LAST:event_btnIniciarActionPerformed

    
